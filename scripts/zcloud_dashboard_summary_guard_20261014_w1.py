#!/usr/bin/env python3
"""Fail-closed, offline gate for one read-only dashboard operator summary.

Never fetches a URL, accesses SQLite, invokes a recovery tool or logs input.
Only canonical text generated by the pinned probe may reach Actions summaries.
"""
from __future__ import annotations

import argparse
import re
import sys

from zcloud_dashboard_external_probe_20261013_w1 import (
    CATEGORIES, ProbeSummary, operator_markdown,
)

MAX_SUMMARY_BYTES = 2048
TIMEOUT_REPORT = (
    "## zCloud · externe dashboardcontrole\n\n"
    "**Status:** API niet aantoonbaar bereikbaar\n"
    "**Reden:** totale tijdslimiet overschreden\n"
    "**Herstel of herstart wordt nooit automatisch uitgevoerd.**\n"
)


def _failure_labels():
    """Derive accepted Dutch category labels from the actual canonical renderer."""
    labels = {}
    for category in sorted(CATEGORIES - {"healthy"}):
        candidate = operator_markdown(
            ProbeSummary("unhealthy", category, 1, False, {category: 1})
        )
        rows = [line for line in candidate.splitlines() if line.startswith("- ")]
        if len(rows) != 1 or not rows[0].endswith(": 1"):
            raise ValueError("noncanonical category")
        label = rows[0][2:-3]
        if label in labels:
            raise ValueError("ambiguous category label")
        labels[label] = category
    return labels


def validate_summary(raw: bytes, probe_rc: int) -> bool:
    """Accept an EXACT reconstructible status, never arbitrary Markdown."""
    if (type(raw) is not bytes or type(probe_rc) is not int or
            probe_rc not in (0, 1, 124) or
            not 0 < len(raw) <= MAX_SUMMARY_BYTES):
        return False
    if probe_rc == 124:
        return raw == TIMEOUT_REPORT.encode("utf-8")
    if not raw.endswith(b"\n") or raw.endswith(b"\n\n"):
        return False
    try:
        source = raw.decode("utf-8", "strict")
        lines = source[:-1].split("\n")
        if (len(lines) < 9 or
                lines[0:2] != ["## zCloud · externe dashboardcontrole", ""] or
                lines[2] != ("**Status:** API bereikbaar" if probe_rc == 0
                             else "**Status:** API niet aantoonbaar bereikbaar") or
                not lines[3].startswith("**Controlepogingen:** ") or
                not lines[4].startswith("**Hersteld na hercontrole:** ")):
            return False
        attempts_text = lines[3][len("**Controlepogingen:** "):]
        if not re.fullmatch(r"[1-6]", attempts_text):
            return False
        attempts = int(attempts_text)
        recovered_text = lines[4][len("**Hersteld na hercontrole:** "):]
        if recovered_text not in ("ja", "nee"):
            return False
        recovered = recovered_text == "ja"
        if recovered != (probe_rc == 0 and attempts > 1):
            return False
        # Exact fixed footer (including origin disclaimer) is reconstructed.
        content_lines = lines[5:-4]
        failures = {}
        if content_lines:
            if content_lines[:2] != ["", "**Waargenomen storingen (aantallen):**"]:
                return False
            accepted = _failure_labels()
            for line in content_lines[2:]:
                match = re.fullmatch(r"- (.+): ([1-6])", line)
                if not match or match.group(1) not in accepted:
                    return False
                category = accepted[match.group(1)]
                if category in failures:
                    return False
                failures[category] = int(match.group(2))
        if sum(failures.values()) != attempts - (probe_rc == 0):
            return False
        expected = operator_markdown(
            ProbeSummary("healthy" if probe_rc == 0 else "unhealthy",
                         None, attempts, recovered, failures)
        ) + "\n"
        return source == expected
    except (ValueError, TypeError, UnicodeError, IndexError):
        return False


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--probe-rc", type=int, required=True)
    args = parser.parse_args(argv)
    # Bound stdin before decoding or parsing. Do not echo rejected bytes.
    raw = sys.stdin.buffer.read(MAX_SUMMARY_BYTES + 1)
    if not validate_summary(raw, args.probe_rc):
        print("DASHBOARD_TRIAGE_INVALID_SUMMARY", file=sys.stderr)
        return 3
    sys.stdout.buffer.write(raw)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
